# Trips — a round trip presented as one route with two legs
# --------------------------------------------------------------------------- #
class TripAssign(BaseModel):
    """Which crew logins work this trip (7.18: every crew member on their own
    phone, up to DEVICES_PER_FLIGHT). `crew_account`/`crew_account_2` are the
    7.11 two-iPad form and still accepted."""

    crew_accounts: list[str] = []
    crew_account: str | None = None
    crew_account_2: str | None = None


def _trip_rows(connection, where="", params=()):
    """Group legs into trips, outbound first, with the route written end to end."""
    rows = _flight_rows(connection, where, params)
    trips, seen = [], {}
    for row in rows:
        row = dict(row)
        root = row["id"] if row["direction"] == "OUTBOUND" else (row["linked_flight_id"] or row["id"])
        if root not in seen:
            seen[root] = {"root_id": root, "legs": [], "trip_type": row["trip_type"],
                          "flight_date": row["flight_date"]}
            trips.append(seen[root])
        seen[root]["legs"].append(row)

    for trip in trips:
        trip["legs"].sort(key=lambda l: 0 if l["direction"] == "OUTBOUND" else 1)
        outbound = trip["legs"][0]
        inbound = trip["legs"][1] if len(trip["legs"]) > 1 else None
        trip["flight_date"] = outbound["flight_date"]
        trip["outbound"] = outbound
        trip["return"] = inbound
        # KTM-DXB-KTM for a round trip, KTM-DXB for one way.
        trip["route"] = (f"{outbound['origin']}-{outbound['destination']}-{inbound['destination']}"
                         if inbound else f"{outbound['origin']}-{outbound['destination']}")
        trip["flight_numbers"] = " / ".join(l["flight_number"] for l in trip["legs"])
        trip["round_trip"] = inbound is not None
        trip["status"] = ("CLOSED" if all(l["status"] == "CLOSED" for l in trip["legs"])
                          else "OPEN" if any(l["status"] == "OPEN" for l in trip["legs"])
                          else "FLOWN")
        trip["fully_assigned"] = all(l.get("crew_account") for l in trip["legs"])
        trip["devices"] = (trip["legs"][0].get("crew_account") or "").split(",") if trip["legs"] and trip["legs"][0].get("crew_account") else []
        trip["groups_formed"] = sum(1 for l in trip["legs"] if l.get("duty_group_id"))
        # 7.12: where each iPad stands, since the two work independently.
        trip["device_status"] = {}
        for device in trip["devices"]:
            root_state = trip_flow.device_state(connection, outbound["id"], device)
            if root_state["completed_at"] or outbound.get("trip_completed_at"):
                trip["device_status"][device] = "FINISHED WHOLE FLIGHT"
                continue
            finished = [trip_flow.leg_finished_for(connection, l, device) for l in trip["legs"]]
            started = [trip_flow.leg_started_for(connection, l, device) for l in trip["legs"]]
            if all(finished):
                trip["device_status"][device] = "ALL SECTORS FINISHED"
            elif any(finished):
                trip["device_status"][device] = "SECOND SECTOR" if started[-1] else "FIRST SECTOR FINISHED"
            elif any(l["status"] != "OPEN" for l in trip["legs"]):
                trip["device_status"][device] = "FINISHED"
            else:
                trip["device_status"][device] = "SELLING / NOT STARTED"
    return trips


@router.get("/trips")
def list_trips(page: int | None = PageParam, page_size: int = PageSizeParam,
               status: str | None = None, user: dict = Depends(current_user)):
    connection = get_connection()
    try:
        # Trips are assembled from legs in Python, so they are paged after grouping.
        if user["role"] in CREW_ROLES:
            trips = _trip_rows(
                connection,
                """WHERE a.crew_account=?
                     AND f.status IN ('OPEN','FLOWN')
                     AND f.flight_date >= date('now','-3 day')""",
                (user["employee_id"],),
            )
        else:
            trips = _trip_rows(connection)
        if status:
            trips = [t for t in trips if t["status"] == status.strip().upper()]
        if page:
            return paginate_list(trips, page, page_size)
        return trips
    finally:
        connection.close()


@router.post("/trips/{root_id}/assign")
def assign_trip(root_id: int, data: TripAssign, user: dict = Depends(requires("groups"))):
    """Put one OBS iPad on both legs of a trip.

    The device stays with the aircraft through the turnaround, so both sectors
    carry the same account. Who is actually selling changes at the turnaround,
    and that is recorded by the crew themselves as a new duty group.
    """
    connection = get_connection()
    try:
        legs = connection.execute(
            "SELECT * FROM flights WHERE id=? OR linked_flight_id=? ORDER BY direction ASC",
            (root_id, root_id),
        ).fetchall()
        if not legs:
            raise HTTPException(status_code=404, detail="Trip not found.")
    finally:
        connection.close()

    accounts = [a.strip().upper() for a in [*data.crew_accounts, data.crew_account or "", data.crew_account_2 or ""]
                if a and a.strip()]
    if not accounts:
        raise HTTPException(status_code=400, detail="Pick at least one crew member.")
    if len(set(accounts)) != len(accounts):
        raise HTTPException(status_code=400, detail="The same crew member was picked twice.")
    if len(accounts) > DEVICES_PER_FLIGHT:
        raise HTTPException(status_code=400, detail=f"A sector takes at most {DEVICES_PER_FLIGHT} crew.")
    for leg in legs:
        if leg["status"] != "OPEN":
            raise HTTPException(status_code=400, detail="This trip has already been flown, so its crew cannot be changed.")
    connection = get_connection()
    try:
        for account in accounts:
            row = connection.execute("SELECT role FROM users WHERE employee_id=? AND active=1", (account,)).fetchone()
            if not row or row["role"] not in CREW_ROLES:
                raise HTTPException(status_code=400, detail=f"{account} is not an active crew login.")
    finally:
        connection.close()
    # Replace whatever was rostered before, on every leg of the trip.
    connection = get_connection()
    try:
        for leg in legs:
            connection.execute("DELETE FROM flight_assignments WHERE flight_id=?", (leg["id"],))
        connection.commit()
    finally:
        connection.close()
    for leg in legs:
        for account in accounts:
            assign_group(AssignmentIn(flight_id=leg["id"], crew_account=account), user=user)

    connection = get_connection()
    try:
        return _trip_rows(connection, "WHERE f.id=? OR f.linked_flight_id=?", (root_id, root_id))[0]
    finally:
        connection.close()


