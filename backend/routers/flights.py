def _flight_rows(connection, where="", params=()):
    return connection.execute(
        f"""SELECT f.*, a.crew_account,
                   d.id AS duty_group_id, d.label AS duty_group_label,
                   d.created_by AS duty_group_created_by, d.locked AS duty_group_locked,
                   (SELECT COUNT(*) FROM duty_group_members m
                     WHERE m.duty_group_id = d.id) AS duty_group_size,
                   (SELECT COUNT(*) FROM reconciliations r
                     WHERE r.flight_id=f.id AND r.status='APPROVED') AS reconciled
            FROM flights f
            LEFT JOIN flight_assignments a ON a.flight_id = f.id
            LEFT JOIN duty_groups d ON d.flight_id = f.id
            {where}
            ORDER BY f.flight_date DESC, f.flight_number, f.direction""",
        params,
    ).fetchall()


@router.get("/flights")
def list_flights(mine_only: bool = False, user: dict = Depends(current_user)):
    """A cabin iPad sees only the flights it is assigned to unless told otherwise."""
    connection = get_connection()
    try:
        if user["role"] == "crew_supervisor":
            # The device sees only the legs it is assigned to, and only while
            # they are still live. Closed flights and other crews' flights stay
            # off the device entirely.
            rows = _flight_rows(
                connection,
                """WHERE a.crew_account=?
                     AND f.status IN ('OPEN','FLOWN')
                     AND f.flight_date >= date('now','-3 day')""",
                (user["employee_id"],),
            )
        elif mine_only:
            rows = _flight_rows(
                connection, "WHERE a.crew_account=?", (user["employee_id"],),
            )
        else:
            rows = _flight_rows(connection)
        return [dict(r) for r in rows]
    finally:
        connection.close()


@router.post("/flights")
def create_flight(data: FlightCreate, user: dict = Depends(requires("inventory"))):
    trip_type = data.trip_type.strip().upper()
    if trip_type not in TRIP_TYPES:
        raise HTTPException(status_code=400, detail="Trip type must be ONE_WAY or ROUND_TRIP.")
    flight_date = validate_date(data.flight_date, "flight date")
    origin = data.origin.strip().upper()
    destination = data.destination.strip().upper()
    if origin == destination:
        raise HTTPException(status_code=400, detail="Origin and destination must be different.")
    number = data.flight_number.strip().upper()

    connection = get_connection()
    try:
        cur = connection.cursor()
        cur.execute(
            """INSERT INTO flights
               (flight_number,flight_date,origin,destination,trip_type,direction,
                passengers,created_by,created_at)
               VALUES (?,?,?,?,?,'OUTBOUND',0,?,?)""",
            (number, flight_date, origin, destination, trip_type, user["employee_id"], now_iso()),
        )
        outbound_id = cur.lastrowid

        return_id = None
        if trip_type == "ROUND_TRIP":
            return_number = (data.return_flight_number or number).strip().upper()
            return_date = validate_date(data.return_flight_date or flight_date, "return flight date")
            cur.execute(
                """INSERT INTO flights
                   (flight_number,flight_date,origin,destination,trip_type,direction,
                    linked_flight_id,passengers,created_by,created_at)
                   VALUES (?,?,?,?,?, 'RETURN', ?,0,?,?)""",
                (return_number, return_date, destination, origin, trip_type,
                 outbound_id, user["employee_id"], now_iso()),
            )
            return_id = cur.lastrowid
            cur.execute("UPDATE flights SET linked_flight_id=? WHERE id=?", (return_id, outbound_id))
        connection.commit()
        rows = _flight_rows(connection, "WHERE f.id IN (?,?)", (outbound_id, return_id or outbound_id))
    except sqlite3.IntegrityError:
        raise HTTPException(
            status_code=400,
            detail="A flight with that number, date and direction already exists.",
        )
    finally:
        connection.close()

    log_action(user, "FLIGHT", "CREATE_FLIGHT",
               f"Created {trip_type.replace('_', ' ').lower()} {number} {origin}-{destination} on {flight_date}.",
               "flight", outbound_id, metadata=data.model_dump())
    return [dict(r) for r in rows]


@router.get("/aircraft-types")
def aircraft_types(user: dict = Depends(current_user)):
    """Fleet types and the seat map each one produces."""
    return [
        {
            "code": code,
            "rows": spec["rows"],
            "layout": spec["layout"],
            "seats": spec["rows"] * sum(len(block) for block in spec["layout"]),
        }
        for code, spec in AIRCRAFT_TYPES.items()
    ]


@router.put("/flights/{flight_id}/aircraft")
def set_aircraft(flight_id: int, data: AircraftUpdate, user: dict = Depends(requires("crew"))):
    aircraft_type = data.aircraft_type.strip().upper()
    if aircraft_type not in AIRCRAFT_TYPES:
        raise HTTPException(
            status_code=400,
            detail=f"Aircraft must be one of: {', '.join(AIRCRAFT_TYPES)}.",
        )
    aircraft = (data.aircraft or "").strip().upper() or None
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        _assert_device_assigned(connection, flight, user)
        _assert_leg_open(flight, "change aircraft")
        _guard_locked_field(user, flight, "aircraft_locked", "Aircraft", data.remarks)
        sold = connection.execute(
            "SELECT COUNT(*) c FROM sales WHERE flight_id=?", (flight_id,)
        ).fetchone()["c"]
        if sold and flight["aircraft_type"] and flight["aircraft_type"] != aircraft_type:
            raise HTTPException(
                status_code=400,
                detail="Sales already exist on this flight, so the aircraft type cannot change "
                       "(the seat map would no longer match the recorded seats).",
            )
        connection.execute(
            """UPDATE flights SET aircraft_type=?, aircraft=?, aircraft_locked=1,
                   aircraft_entered_by=?, aircraft_entered_at=? WHERE id=?""",
            (aircraft_type, aircraft, user["employee_id"], now_iso(), flight_id),
        )
        connection.commit()
        row = _flight_rows(connection, "WHERE f.id=?", (flight_id,))[0]
    finally:
        connection.close()

    changed = bool(flight["aircraft_locked"])
    label = f"{aircraft_type}{f' ({aircraft})' if aircraft else ''}"
    log_action(
        user, "FLIGHT", "UPDATE_AIRCRAFT" if changed else "SET_AIRCRAFT",
        (f"Corrected aircraft on {flight['flight_number']} to {label}. Remarks: {data.remarks}"
         if changed else f"Set aircraft {label} on {flight['flight_number']}."),
        "flight", flight_id,
        metadata={"aircraft_type": aircraft_type, "aircraft": aircraft, "remarks": data.remarks},
    )
    return dict(row)


