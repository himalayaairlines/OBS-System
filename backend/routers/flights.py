@router.post("/flights/{flight_id}/duty-group")
def create_duty_group(flight_id: int, data: DutyGroupIn, user: dict = Depends(requires("crew"))):
    """The crew pick their own names at the start of a sector.

    This is the step that replaces ground-side crew assignment. The group
    belongs to this leg alone: on a round trip the return sector forms its own,
    even when the same people are chosen again, which is what keeps the two
    sectors' commission apart.
    """
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        _assert_device_assigned(connection, flight, user)
        _assert_leg_open(flight, "form a duty group")

        existing = _duty_group_row(connection, flight_id)
        if existing:
            # An offline queue replaying its own creation is not an error.
            if data.client_ref and existing.get("client_ref") == data.client_ref:
                return existing
            # 7.18: another crew member's phone entered the names first. Theirs
            # stands; a different list from this phone is shown to Management
            # as a difference rather than lost or refused.
            mine = sorted(set(data.member_ids))
            theirs = sorted(m["id"] for m in existing["members"])
            if mine != theirs:
                names = {r["id"]: r["name"] for r in connection.execute(
                    f"SELECT id, name FROM crew_members WHERE id IN ({','.join('?' * len(mine)) or 'NULL'})", mine)}
                trip_flow.record_conflict(
                    connection, flight_id, user["employee_id"], "duty_group",
                    ", ".join(m["name"] for m in existing["members"]), existing.get("created_by"),
                    ", ".join(names.get(i, f"#{i}") for i in mine), now_iso())
                connection.commit()
            return {**existing, "already_formed": True}

        _validate_members(connection, data.member_ids)
        label = (f"{flight['flight_number']} / {flight['flight_date']} / "
                 f"{'OUT' if flight['direction'] == 'OUTBOUND' else 'RET'}")
        try:
            cur = connection.execute(
                """INSERT INTO duty_groups(flight_id,client_ref,label,created_by,created_at)
                   VALUES (?,?,?,?,?)""",
                (flight_id, data.client_ref, label, user["employee_id"], now_iso()),
            )
        except sqlite3.IntegrityError:
            # Two queued attempts raced; the first one won and is the answer.
            connection.rollback()
            group = _duty_group_row(connection, flight_id)
            if group:
                return group
            raise
        group_id = cur.lastrowid
        for member_id in data.member_ids:
            connection.execute(
                "INSERT INTO duty_group_members(duty_group_id,crew_member_id) VALUES (?,?)",
                (group_id, member_id),
            )
        connection.commit()
        group = _duty_group_row(connection, flight_id)
    finally:
        connection.close()

    names = ", ".join(m["name"] for m in group["members"])
    log_action(
        user, "DUTY GROUP", "CREATE",
        f"Duty group formed for {label}: {names}.",
        "duty_group", group["id"],
        metadata={"flight_id": flight_id, "members": data.member_ids},
    )
    return group


@router.put("/flights/{flight_id}/duty-group")
def amend_duty_group(flight_id: int, data: DutyGroupAmend, user: dict = Depends(requires("crew"))):
    """Change who is in the group.

    The crew get one correction, and it needs a reason. The membership is the
    historical basis for that sector's commission, so after that one change it
    stands and only Management may alter it, with remarks of their own.
    """
