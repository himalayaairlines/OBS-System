@router.get("/assignments")
def list_assignments(flight_date: str | None = None, user: dict = Depends(requires("groups"))):
    connection = get_connection()
    try:
        where, params = "", []
        if flight_date:
            where = "WHERE f.flight_date=?"
            params.append(validate_date(flight_date, "flight date"))
        rows = connection.execute(
            f"""SELECT a.*, f.flight_number, f.flight_date, f.origin, f.destination,
                       f.direction, f.trip_type, f.aircraft,
                       d.label AS duty_group_label, d.created_by AS duty_group_created_by,
                       (SELECT COUNT(*) FROM duty_group_members m
                         WHERE m.duty_group_id = d.id) AS duty_group_size
                FROM flight_assignments a
                JOIN flights f ON f.id = a.flight_id
                LEFT JOIN duty_groups d ON d.flight_id = f.id
                {where}
                ORDER BY f.flight_date DESC, f.flight_number, f.direction""",
            params,
        ).fetchall()
        return [dict(r) for r in rows]
    finally:
        connection.close()


@router.post("/assignments")
def assign_group(data: AssignmentIn, user: dict = Depends(requires("groups"))):
    """Put an OBS iPad account on a leg.

    This is the whole of the ground-side crew step now. Which people sell is
    decided on board and recorded as a duty group.
    """
    account = data.crew_account.strip().upper()
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (data.flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        if flight["status"] != "OPEN":
            raise HTTPException(
                status_code=400,
                detail="This sector has already been flown, so its device cannot be reassigned.",
            )

        row = connection.execute(
            "SELECT role FROM users WHERE employee_id=? AND active=1", (account,)
        ).fetchone()
        if not row or row["role"] not in CREW_ROLES:
            raise HTTPException(
                status_code=400, detail=f"{account} is not an active crew login.",
            )

        # 7.11: an iPad may be rostered to several trips on one day. It sees
        # the next trip only once the current one is finished, so there is no
        # clash check any more. A leg carries at most DEVICES_PER_FLIGHT iPads.
        count = connection.execute(
            "SELECT COUNT(*) c FROM flight_assignments WHERE flight_id=? AND crew_account<>?",
            (data.flight_id, account)).fetchone()["c"]
        if count >= DEVICES_PER_FLIGHT:
            raise HTTPException(
                status_code=400,
                detail=f"This sector already has {DEVICES_PER_FLIGHT} crew. Remove one first.",
            )
        connection.execute(
            """INSERT INTO flight_assignments
                   (flight_id,crew_account,assigned_by,assigned_at)
               VALUES (?,?,?,?)
               ON CONFLICT(flight_id, crew_account) DO UPDATE SET
                   assigned_by=excluded.assigned_by,
                   assigned_at=excluded.assigned_at""",
            (data.flight_id, account, user["employee_id"], now_iso()),
        )
        connection.commit()
    finally:
        connection.close()

    log_action(user, "FLIGHT", "ASSIGN_DEVICE",
               f"Assigned {account} to {flight['flight_number']} "
               f"({flight['direction'].lower()}) on {flight['flight_date']}.",
               "flight", data.flight_id, metadata={"crew_account": account})
    return {"status": "success", "flight_id": data.flight_id, "crew_account": account}


@router.delete("/assignments/{flight_id}")
def unassign(flight_id: int, user: dict = Depends(requires("groups"))):
    connection = get_connection()
    try:
        sold = connection.execute(
            "SELECT COUNT(*) c FROM sales WHERE flight_id=?", (flight_id,)
        ).fetchone()["c"]
        if sold:
            raise HTTPException(
                status_code=400,
                detail="Sales already exist on this flight, so the device cannot be unassigned.",
            )
        if connection.execute(
            "SELECT 1 FROM duty_groups WHERE flight_id=?", (flight_id,)
        ).fetchone():
            raise HTTPException(
                status_code=400,
                detail="The crew have already formed a duty group on this sector.",
            )
        connection.execute("DELETE FROM flight_assignments WHERE flight_id=?", (flight_id,))
        connection.commit()
    finally:
        connection.close()
    log_action(user, "FLIGHT", "UNASSIGN_DEVICE", "Removed the OBS device assignment.",
               "flight", flight_id)
    return {"status": "success"}
