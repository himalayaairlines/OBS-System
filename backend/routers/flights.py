"""Flight legs, aircraft/PAX capture, duty groups and flight assignments.

Ownership of each field:
  * Inventory  -> flight number, date, origin, destination, trip type, and
                  which OBS iPad account works the trip
  * Crew       -> aircraft registration, PAX load, and the duty group: the
                  people actually working this sector, chosen on board
  * Management -> may amend a locked duty group, with remarks
"""

