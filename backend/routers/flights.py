@router.put("/flights/{flight_id}/aircraft")
def set_aircraft(flight_id: int, data: AircraftUpdate, user: dict = Depends(requires("crew"))):
    aircraft_type = data.aircraft_type.strip().upper()
    if aircraft_type not in AIRCRAFT_TYPES:
        raise HTTPException(
            status_code=400,
            detail=f"Aircraft must be one of: {', '.join(AIRCRAFT_TYPES)}.",
        )
    aircraft = (data.aircraft or "").strip().upper() or None
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        _assert_device_assigned(connection, flight, user)
        if flight["aircraft_type"] == aircraft_type and (flight["aircraft"] or None) == aircraft:
            return dict(_flight_rows(connection, "WHERE f.id=?", (flight_id,))[0])  # replayed offline save
        if (_is_device(connection, flight, user) and flight["aircraft_locked"]
                and flight["aircraft_entered_by"] and flight["aircraft_entered_by"] != user["employee_id"]):
            # 7.15: the other iPad set it first (both worked offline). Keep that
            # value and show the difference to Management instead of overwriting.
            label = f"{aircraft_type}{f' ({aircraft})' if aircraft else ''}"
            kept = f"{flight['aircraft_type']}{f' ({flight['aircraft']})' if flight['aircraft'] else ''}"
            trip_flow.record_conflict(connection, flight_id, user["employee_id"], "aircraft", kept,
                                      flight["aircraft_entered_by"], label, now_iso())
            connection.commit()
            log_action(user, "FLIGHT", "AIRCRAFT_CONFLICT",
                       f"iPad {user['employee_id']} sent aircraft {label} for {flight['flight_number']}; "
                       f"{kept} from {flight['aircraft_entered_by']} kept. Shown to Management as a difference.",
                       "flight", flight_id, status="WARNING")
            return {**dict(_flight_rows(connection, "WHERE f.id=?", (flight_id,))[0]), "conflict": True}
        _assert_leg_open(flight, "change aircraft", connection, user)
        _guard_locked_field(user, flight, "aircraft_locked", "Aircraft", data.remarks)
        sold = connection.execute(
            "SELECT COUNT(*) c FROM sales WHERE flight_id=?", (flight_id,)
        ).fetchone()["c"]
        if sold and flight["aircraft_type"] and flight["aircraft_type"] != aircraft_type:
            raise HTTPException(
                status_code=400,
                detail="Sales already exist on this flight, so the aircraft type cannot change "
                       "(the seat map would no longer match the recorded seats).",
            )
        connection.execute(
            """UPDATE flights SET aircraft_type=?, aircraft=?, aircraft_locked=1,
                   aircraft_entered_by=?, aircraft_entered_at=? WHERE id=?""",
            (aircraft_type, aircraft, user["employee_id"], now_iso(), flight_id),
        )
        connection.commit()
        row = _flight_rows(connection, "WHERE f.id=?", (flight_id,))[0]
    finally:
        connection.close()

    changed = bool(flight["aircraft_locked"])
    label = f"{aircraft_type}{f' ({aircraft})' if aircraft else ''}"
    log_action(
        user, "FLIGHT", "UPDATE_AIRCRAFT" if changed else "SET_AIRCRAFT",
        (f"Corrected aircraft on {flight['flight_number']} to {label}. Remarks: {data.remarks}"
         if changed else f"Set aircraft {label} on {flight['flight_number']}."),
        "flight", flight_id,
        metadata={"aircraft_type": aircraft_type, "aircraft": aircraft, "remarks": data.remarks},
    )
    return dict(row)


