def _duty_group_row(connection, flight_id: int):
    row = connection.execute(
        "SELECT * FROM duty_groups WHERE flight_id=?", (flight_id,)
    ).fetchone()
    if not row:
        return None
    group = dict(row)
    group["members"] = [dict(r) for r in connection.execute(
        """SELECT m.id, m.crew_code, m.name, m.position
           FROM duty_group_members dm JOIN crew_members m ON m.id = dm.crew_member_id
           WHERE dm.duty_group_id=?
           ORDER BY CASE m.position WHEN 'Purser' THEN 0
                                    WHEN 'Senior Cabin Crew' THEN 1 ELSE 2 END, m.name""",
        (group["id"],),
    ).fetchall()]
    group["size"] = DUTY_GROUP_SIZE
    group["min_size"] = DUTY_GROUP_MIN
    group["max_size"] = DUTY_GROUP_MAX
    group["amend_limit"] = DUTY_GROUP_AMEND_LIMIT
    # Whether the iPad still has its one correction. Management are not bound
    # by this; their corrections are governed by remarks and the audit trail.
    group["may_amend"] = int(group.get("amend_count") or 0) < DUTY_GROUP_AMEND_LIMIT
    return group


def _validate_members(connection, member_ids):
    if len(set(member_ids)) != len(member_ids):
        raise HTTPException(status_code=400, detail="The same crew member cannot be picked twice.")
    if not DUTY_GROUP_MIN <= len(member_ids) <= DUTY_GROUP_MAX:
        raise HTTPException(
            status_code=400,
            detail=f"A duty group is between {DUTY_GROUP_MIN} and {DUTY_GROUP_MAX} crew members. "
                   f"{len(member_ids)} were selected.",
        )
    for member_id in member_ids:
        if not connection.execute(
            "SELECT 1 FROM crew_members WHERE id=? AND active=1", (member_id,)
        ).fetchone():
            raise HTTPException(
                status_code=400, detail="One of the selected crew members is not on the active roster."
            )


