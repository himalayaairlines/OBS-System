@router.get("/crew-roster")
def crew_roster(user: dict = Depends(current_user)):
    """The active crew roster.

    The iPad needs this to let the crew pick their own names, so the cabin
    account reads it too, not only the ground roles.
    """
    if not permissions_for(user["role"]) & {"groups", "crew", "crew_members"}:
        raise HTTPException(status_code=403, detail="You do not have permission to perform this action.")
    connection = get_connection()
    try:
        rows = connection.execute(
            """SELECT id, crew_code, name, position FROM crew_members WHERE active=1
               ORDER BY CASE position WHEN 'Purser' THEN 0
                                      WHEN 'Senior Cabin Crew' THEN 1 ELSE 2 END, name"""
        ).fetchall()
        return [dict(r) for r in rows]
    finally:
        connection.close()


