@router.post("/flights/{flight_id}/duty-group")
def create_duty_group(flight_id: int, data: DutyGroupIn, user: dict = Depends(requires("crew"))):
    """The crew pick their own names at the start of a sector.

    This is the step that replaces ground-side crew assignment. The group
    belongs to this leg alone: on a round trip the return sector forms its own,
    even when the same people are chosen again, which is what keeps the two
    sectors' commission apart.
    """
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        _assert_device_assigned(connection, flight, user)
        _assert_leg_open(flight, "form a duty group")

        existing = _duty_group_row(connection, flight_id)
        if existing:
            # An offline queue replaying its own creation is not an error.
            if data.client_ref and existing.get("client_ref") == data.client_ref:
                return existing
            raise HTTPException(
                status_code=400,
                detail="A duty group has already been formed for this sector.",
            )

        _validate_members(connection, data.member_ids)
        label = (f"{flight['flight_number']} / {flight['flight_date']} / "
                 f"{'OUT' if flight['direction'] == 'OUTBOUND' else 'RET'}")
        try:
            cur = connection.execute(
                """INSERT INTO duty_groups(flight_id,client_ref,label,created_by,created_at)
                   VALUES (?,?,?,?,?)""",
                (flight_id, data.client_ref, label, user["employee_id"], now_iso()),
            )
        except sqlite3.IntegrityError:
            # Two queued attempts raced; the first one won and is the answer.
            connection.rollback()
            group = _duty_group_row(connection, flight_id)
            if group:
                return group
            raise
        group_id = cur.lastrowid
        for member_id in data.member_ids:
            connection.execute(
                "INSERT INTO duty_group_members(duty_group_id,crew_member_id) VALUES (?,?)",
                (group_id, member_id),
            )
        connection.commit()
        group = _duty_group_row(connection, flight_id)
    finally:
        connection.close()

    names = ", ".join(m["name"] for m in group["members"])
    log_action(
        user, "DUTY GROUP", "CREATE",
        f"Duty group formed for {label}: {names}.",
        "duty_group", group["id"],
        metadata={"flight_id": flight_id, "members": data.member_ids},
    )
    return group


@router.put("/flights/{flight_id}/duty-group")
def amend_duty_group(flight_id: int, data: DutyGroupAmend, user: dict = Depends(requires("crew"))):
    """Change who is in the group.

    The crew get one correction, and it needs a reason. The membership is the
    historical basis for that sector's commission, so after that one change it
    stands and only Management may alter it, with remarks of their own.
    """
    if not (data.remarks or "").strip():
        raise HTTPException(status_code=400, detail="Remarks are mandatory when changing a duty group.")
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        group = _duty_group_row(connection, flight_id)
        if not group:
            raise HTTPException(status_code=404, detail="No duty group has been formed for this sector.")

        by_management = "groups_manage" in permissions_for(user["role"])
        if not by_management:
            _assert_device_assigned(connection, flight, user)
            _assert_leg_open(flight, "change the duty group")
            if not group["may_amend"]:
                raise HTTPException(
                    status_code=400,
                    detail=("This duty group has already been corrected once and can no "
                            "longer be changed on the iPad. Ask Management to change it."),
                )

        _validate_members(connection, data.member_ids)

        # A member who has already sold cannot be dropped: their sales would be
        # left pointing at somebody who was never on the sector.
        sold_ids = {r["sold_by_crew_member_id"] for r in connection.execute(
            "SELECT DISTINCT sold_by_crew_member_id FROM sales WHERE flight_id=?", (flight_id,)
        ).fetchall() if r["sold_by_crew_member_id"]}
        dropped = sold_ids - set(data.member_ids)
        if dropped:
            names = [r["name"] for r in connection.execute(
                f"SELECT name FROM crew_members WHERE id IN ({','.join('?' * len(dropped))})",
                tuple(dropped),
            ).fetchall()]
            raise HTTPException(
                status_code=400,
                detail=f"{', '.join(names)} already recorded sales on this sector and cannot be removed.",
            )

        before = [m["id"] for m in group["members"]]
        connection.execute("DELETE FROM duty_group_members WHERE duty_group_id=?", (group["id"],))
        for member_id in data.member_ids:
            connection.execute(
                "INSERT INTO duty_group_members(duty_group_id,crew_member_id) VALUES (?,?)",
                (group["id"], member_id),
            )
        connection.execute(
            """UPDATE duty_groups
               SET amended_by=?, amended_at=?, amend_remarks=?,
                   amend_count = amend_count + ?
               WHERE id=?""",
            (user["employee_id"], now_iso(), data.remarks.strip(),
             0 if by_management else 1, group["id"]),
        )
        connection.commit()
        updated = _duty_group_row(connection, flight_id)
    finally:
        connection.close()

    log_action(
        user, "DUTY GROUP", "AMEND",
        f"Duty group changed on {group['label']}. Remarks: {data.remarks.strip()}",
        "duty_group", group["id"],
        metadata={"before": before, "after": data.member_ids, "remarks": data.remarks.strip()},
    )
    return updated


# --------------------------------------------------------------------------- #
# Trips — a round trip presented as one route with two legs
# --------------------------------------------------------------------------- #
class TripAssign(BaseModel):
    """Which OBS iPad works this trip. Crew names are chosen on board."""

    crew_account: str


def _trip_rows(connection, where="", params=()):
    """Group legs into trips, outbound first, with the route written end to end."""
    rows = _flight_rows(connection, where, params)
    trips, seen = [], {}
    for row in rows:
        row = dict(row)
        root = row["id"] if row["direction"] == "OUTBOUND" else (row["linked_flight_id"] or row["id"])
        if root not in seen:
            seen[root] = {"root_id": root, "legs": [], "trip_type": row["trip_type"],
                          "flight_date": row["flight_date"]}
            trips.append(seen[root])
        seen[root]["legs"].append(row)

    for trip in trips:
        trip["legs"].sort(key=lambda l: 0 if l["direction"] == "OUTBOUND" else 1)
        outbound = trip["legs"][0]
        inbound = trip["legs"][1] if len(trip["legs"]) > 1 else None
        trip["flight_date"] = outbound["flight_date"]
        trip["outbound"] = outbound
        trip["return"] = inbound
        # KTM-DXB-KTM for a round trip, KTM-DXB for one way.
        trip["route"] = (f"{outbound['origin']}-{outbound['destination']}-{inbound['destination']}"
                         if inbound else f"{outbound['origin']}-{outbound['destination']}")
        trip["flight_numbers"] = " / ".join(l["flight_number"] for l in trip["legs"])
        trip["round_trip"] = inbound is not None
        trip["status"] = ("CLOSED" if all(l["status"] == "CLOSED" for l in trip["legs"])
                          else "OPEN" if any(l["status"] == "OPEN" for l in trip["legs"])
                          else "FLOWN")
        trip["fully_assigned"] = all(l.get("crew_account") for l in trip["legs"])
        trip["groups_formed"] = sum(1 for l in trip["legs"] if l.get("duty_group_id"))
    return trips


@router.get("/trips")
def list_trips(page: int | None = PageParam, page_size: int = PageSizeParam,
               status: str | None = None, user: dict = Depends(current_user)):
    connection = get_connection()
    try:
        # Trips are assembled from legs in Python, so they are paged after grouping.
        if user["role"] == "crew_supervisor":
            trips = _trip_rows(
                connection,
                """WHERE a.crew_account=?
                     AND f.status IN ('OPEN','FLOWN')
                     AND f.flight_date >= date('now','-3 day')""",
                (user["employee_id"],),
            )
        else:
            trips = _trip_rows(connection)
        if status:
            trips = [t for t in trips if t["status"] == status.strip().upper()]
        if page:
            return paginate_list(trips, page, page_size)
        return trips
    finally:
        connection.close()


@router.post("/trips/{root_id}/assign")
def assign_trip(root_id: int, data: TripAssign, user: dict = Depends(requires("groups"))):
    """Put one OBS iPad on both legs of a trip.

    The device stays with the aircraft through the turnaround, so both sectors
    carry the same account. Who is actually selling changes at the turnaround,
    and that is recorded by the crew themselves as a new duty group.
    """
    connection = get_connection()
    try:
        legs = connection.execute(
            "SELECT * FROM flights WHERE id=? OR linked_flight_id=? ORDER BY direction ASC",
            (root_id, root_id),
        ).fetchall()
        if not legs:
            raise HTTPException(status_code=404, detail="Trip not found.")
    finally:
        connection.close()

    for leg in legs:
        assign_group(AssignmentIn(flight_id=leg["id"], crew_account=data.crew_account), user=user)

    connection = get_connection()
    try:
        return _trip_rows(connection, "WHERE f.id=? OR f.linked_flight_id=?", (root_id, root_id))[0]
    finally:
        connection.close()


