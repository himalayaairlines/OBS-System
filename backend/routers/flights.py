def _assert_device_assigned(connection, flight, user):
    """The caller's iPad must be the one rostered to this leg.

    Without this any cabin account could set the PAX load on another crew's
    flight simply by calling the endpoint with a different id, which would move
    that flight's RPP.
    """
    if permissions_for(user["role"]) >= {"sales_edit"}:
        return  # management correcting after the fact
    assignment = connection.execute(
        "SELECT crew_account FROM flight_assignments WHERE flight_id=?", (flight["id"],)
    ).fetchone()
    if not assignment:
        raise HTTPException(
            status_code=400, detail="No OBS device is assigned to this flight yet."
        )
    if user["employee_id"] != assignment["crew_account"]:
        raise HTTPException(
            status_code=403, detail="This device is not assigned to that flight."
        )


def _assert_leg_open(flight, action="change"):
    trip_flow.assert_started(flight, action)
    if flight["status"] == "FLOWN":
        raise HTTPException(
            status_code=400,
            detail=f"Selling is finished on this sector, so it can no longer {action}.",
        )
    if flight["status"] != "OPEN":
        raise HTTPException(
            status_code=400, detail="This flight has been closed and reconciled.",
        )


def _guard_locked_field(user, flight, lock_column, label, remarks):
    """The value may be set once. Changing it afterwards needs a reason.

    There is one cabin account, so the old "crew sets, supervisor corrects"
    split no longer applies. What protects the figure now is the audit trail:
    a change is only accepted for today's flight and only with remarks.
    """
    if not flight[lock_column]:
        return
    if permissions_for(user["role"]) >= {"sales_edit"}:
        return  # management correcting a historical flight
    if flight["flight_date"] != today_iso():
        raise HTTPException(
            status_code=403,
            detail=f"The {label} of a past flight can only be corrected by Management.",
        )
    if not (remarks or "").strip():
        raise HTTPException(
            status_code=400,
            detail=f"Remarks are mandatory when changing the {label}.",
        )


@router.put("/flights/{flight_id}/finish")
def finish_flight(flight_id: int, user: dict = Depends(requires("crew"))):
    """Close selling on a leg.

    On a round trip both legs are worked from the same iPad account, so the
    outbound group must hand over explicitly. Once finished, no further sale can
    be recorded against this leg and the return leg becomes the active one, which
    is what keeps each group's commission separate.
    """
    connection = get_connection()
    try:
        flight = connection.execute("SELECT * FROM flights WHERE id=?", (flight_id,)).fetchone()
        if not flight:
            raise HTTPException(status_code=404, detail="Flight not found.")
        if flight["status"] == "CLOSED":
            raise HTTPException(status_code=400, detail="This flight is already closed.")
        if flight["status"] == "FLOWN":
            raise HTTPException(status_code=400, detail="This flight has already been finished.")

        _assert_device_assigned(connection, flight, user)
        trip_flow.assert_started(flight, "finish it")

        totals = connection.execute(
            """SELECT COALESCE(SUM(CASE WHEN sale_type='NORMAL' THEN npr_amount END),0) AS revenue,
                      COUNT(DISTINCT order_ref) AS orders
               FROM sales WHERE flight_id=?""",
            (flight_id,),
        ).fetchone()

        connection.execute(
            "UPDATE flights SET status='FLOWN', finished_by=?, finished_at=? WHERE id=?",
            (user["employee_id"], now_iso(), flight_id),
        )
        connection.commit()
        row = _flight_rows(connection, "WHERE f.id=?", (flight_id,))[0]
    finally:
        connection.close()

    log_action(user, "FLIGHT", "FINISH_FLIGHT",
               f"Finished selling on {flight['flight_number']} ({flight['direction'].lower()}). "
               f"{totals['orders']} transaction(s), NPR {float(totals['revenue'] or 0):,.2f}.",
               "flight", flight_id)
    return {
        **dict(row),
        "revenue_npr": round(float(totals["revenue"] or 0), 2),
        "transactions": int(totals["orders"] or 0),
    }


